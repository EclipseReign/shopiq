create function public.catalog_filtered(p jsonb default '{}')
returns table(id bigint,category_id bigint,category_name text,name text,parsed_price numeric,rating numeric,reviews_count bigint,
  image_url text,product_url text,scraped_at timestamptz,city_id text,brand text,external_id text)
language plpgsql stable set search_path='' set statement_timeout='8s' as $$
declare cid bigint=nullif(p->>'categoryId','')::bigint; city text=nullif(p->>'cityId','');
  search_text text=trim(coalesce(p->>'search','')); from_date date=nullif(p->>'dateFrom','')::date; to_date date=nullif(p->>'dateTo','')::date;
begin
  if length(search_text)>200 or (city is not null and city !~ '^\d{9}$') or from_date>to_date then raise exception 'Invalid filters';end if;
  return query with recursive selected(category) as (
    select c.id from public.categories c where c.id=cid
    union select c.id from public.categories c join selected s on c.parent_id=s.category
  ) select pr.id,pr.category_id,c.name,pr.name,case when city is null then pr.parsed_price else cp.parsed_price end,
    pr.rating,pr.reviews_count,pr.image_url,pr.product_url,case when city is null then pr.scraped_at else cp.scraped_at end,
    case when city is null then pr.city_id else cp.city_id end,pr.brand,pr.external_id
  from public.products pr left join public.categories c on c.id=pr.category_id
  left join public.product_city_prices cp on cp.product_id=pr.id and cp.city_id=city
  where (city is null or cp.product_id is not null)
    and (cid is null or pr.category_id in(select category from selected) or exists(select 1 from public.product_categories pc where pc.product_id=pr.id and pc.category_id in(select category from selected)))
    and (search_text='' or position(lower(search_text) in lower(pr.name||' '||coalesce(pr.brand,'')))>0)
    and (from_date is null or (case when city is null then pr.scraped_at else cp.scraped_at end)>=from_date::timestamp at time zone 'UTC')
    and (to_date is null or (case when city is null then pr.scraped_at else cp.scraped_at end)<(to_date+1)::timestamp at time zone 'UTC');
end $$;

create function public.catalog_products(p jsonb default '{}') returns jsonb language plpgsql stable set search_path='' set statement_timeout='8s' as $$
declare page_number integer=coalesce(nullif(p->>'page','')::integer,1); size integer=coalesce(nullif(p->>'pageSize','')::integer,25);
  sorting text=coalesce(nullif(p->>'sort',''),'default');result jsonb;
begin
  if page_number<1 or page_number>1000000 or size<1 or size>100 or sorting not in('default','price-asc','price-desc','rating','reviews') then raise exception 'Invalid pagination';end if;
  with filtered as materialized(select * from public.catalog_filtered(p)),selected as(
    select * from filtered f order by
      case when sorting='price-asc' then f.parsed_price end asc nulls last,
      case when sorting='price-desc' then f.parsed_price end desc nulls last,
      case when sorting='rating' then f.rating end desc nulls last,
      case when sorting='reviews' then f.reviews_count end desc nulls last,
      case when sorting='default' then f.scraped_at end desc nulls last,f.id desc
    limit size offset (page_number::bigint-1)*size
  ) select jsonb_build_object('products',coalesce((select jsonb_agg(to_jsonb(s)) from selected s),'[]'::jsonb),
    'pagination',jsonb_build_object('page',page_number,'pageSize',size,'total',(select count(*) from filtered),
    'pages',ceil((select count(*) from filtered)::numeric/size))) into result;
  return result;
end $$;

create function public.catalog_overview(p jsonb default '{}') returns jsonb language sql stable set search_path='' set statement_timeout='8s' as $$
select jsonb_build_object('overview',to_jsonb(metrics)) from (
  select count(*) products_count,count(distinct category_id) categories_count,count(parsed_price) priced_count,
    avg(parsed_price) average_price,min(parsed_price) min_price,max(parsed_price) max_price,sum(reviews_count) reviews_count,
    count(reviews_count) reviewed_count,avg(rating) average_rating,count(rating) rated_count,max(scraped_at) last_updated
  from public.catalog_filtered(p)
) metrics $$;

create function public.catalog_categories(parent bigint default null) returns jsonb language sql stable set search_path='' set statement_timeout='8s' as $$
with recursive tree(root,id) as (
  select id,id from public.categories where (parent is null and parent_id is null) or parent_id=parent
  union select t.root,c.id from public.categories c join tree t on c.parent_id=t.id
),members as(
  select t.root,p.id from tree t join public.products p on p.category_id=t.id
  union select t.root,pc.product_id from tree t join public.product_categories pc on pc.category_id=t.id
),metrics as(
  select m.root,count(p.id) products_count,avg(p.parsed_price) average_price,sum(p.reviews_count) reviews_count,max(p.scraped_at) last_updated
  from members m join public.products p on p.id=m.id group by m.root
),result as(
  select c.id,c.name,c.parent_id,c.level,c.source_active,c.source_code,
    exists(select 1 from public.categories child where child.parent_id=c.id) has_children,
    coalesce(m.products_count,0) products_count,m.average_price,m.reviews_count,m.last_updated
  from public.categories c left join metrics m on m.root=c.id
  where (parent is null and c.parent_id is null) or c.parent_id=parent
  order by coalesce(m.products_count,0) desc,c.name,c.id
) select jsonb_build_object('categories',coalesce(jsonb_agg(to_jsonb(result)),'[]'::jsonb)) from result $$;

create function public.catalog_category(category bigint) returns jsonb language plpgsql stable set search_path='' as $$
declare result jsonb; begin
  select to_jsonb(c)||jsonb_build_object('can_scrape',c.source_active=1) into result from public.categories c where c.id=category;
  if result is null then return null;end if;
  return jsonb_build_object('category',result||(public.catalog_overview(jsonb_build_object('categoryId',category))->'overview'));
end $$;
