create unique index collection_one_active_idx on public.collection_runs((1)) where status in ('running','cancelling');
create index collection_runs_user_idx on public.collection_runs(requested_by);
create table public.collection_tasks (
  run_id uuid references public.collection_runs(id) on delete cascade, category_id bigint references public.categories(id),
  city_id text not null,status text not null default 'pending',next_page integer not null default 0,
  expected_initial integer,expected_latest integer,page_size integer,found_count integer not null default 0,
  invalid_count integer not null default 0,pages_done integer not null default 0,error text,updated_at timestamptz not null default now(),
