create index collection_tasks_category_idx on public.collection_tasks(category_id);
create index collection_tasks_status_idx on public.collection_tasks(run_id,status);
create table public.collection_pages (
  run_id uuid not null,category_id bigint not null,page integer not null,signature text not null,
  primary key(run_id,category_id,page), unique(run_id,category_id,signature),
