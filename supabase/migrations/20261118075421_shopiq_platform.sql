create table public.categories (
  id bigint generated by default as identity primary key,
  name text not null, url text, parent_id bigint references public.categories(id), level integer not null default 0,
  source_code text unique, source_active integer not null default 0, discovered_at timestamptz
);
create index categories_parent_idx on public.categories(parent_id);
create table public.products (
  id bigint generated by default as identity primary key,
  category_id bigint references public.categories(id), name text not null, price text,
  parsed_price numeric, brand text, rating numeric, reviews_count bigint, image_url text,
  external_id text, product_url text, product_key text unique not null, city_id text,
  scraped_at timestamptz not null default now(), computed_revenue numeric,
  check (parsed_price is null or parsed_price >= 0), check (rating is null or rating between 0 and 5)
);
create index products_category_date_idx on public.products(category_id,scraped_at desc,id desc);
create index products_date_idx on public.products(scraped_at desc,id desc);
create index products_price_idx on public.products(parsed_price,id);
create index products_external_idx on public.products(external_id);
create table public.product_categories (
  product_id bigint references public.products(id) on delete cascade,
  category_id bigint references public.categories(id), primary key(product_id,category_id)
);
create index product_categories_category_idx on public.product_categories(category_id,product_id);
create table public.product_city_prices (
  product_id bigint references public.products(id) on delete cascade, city_id text not null,
  parsed_price numeric, scraped_at timestamptz not null default now(), primary key(product_id,city_id)
);
create index product_city_prices_city_idx on public.product_city_prices(city_id,parsed_price,product_id);
create table public.price_history (
  id bigint generated by default as identity primary key, product_id bigint references public.products(id) on delete cascade,
  city_id text not null, parsed_price numeric not null, scraped_at timestamptz not null default now()
);
create index price_history_product_idx on public.price_history(product_id,city_id,scraped_at desc);
create table public.catalog_discoveries (
  id uuid primary key default gen_random_uuid(),city_id text not null,status text not null,
  started_at timestamptz not null default now(),finished_at timestamptz,categories_count integer,leaves_count integer,error text
);
create table public.collection_runs (
  id uuid primary key default gen_random_uuid(),status text not null default 'running',
  started_at timestamptz not null default now(),finished_at timestamptz,options jsonb not null default '{}',
  progress jsonb not null default '{}',error text,requested_by uuid references auth.users(id)
