-- Mutating RPCs are service-role-only. The Worker verifies the user and supplies
-- their immutable Auth ID. Row locks make retries and simultaneous approvals safe.
create function public.import_store_feed(store uuid,actor uuid,xml text,hash text,items jsonb,expected_version integer,removed text[] default '{}')
returns jsonb language plpgsql set search_path='' as $$
declare prior public.store_feeds;missing text[];next_version integer;begin
  perform 1 from public.stores s where s.id=store and s.owner_id=actor for update;
  if not found then raise exception 'Store not found';end if;
  select * into prior from public.store_feeds f where f.store_id=store for update;
  if expected_version is null or coalesce(prior.version,0)<>expected_version then raise exception 'Feed changed. Reload before importing.';end if;
  if prior.source_hash=hash then return jsonb_build_object('version',prior.version,'unchanged',true);end if;
  select array_agg(old->>'sku') into missing from jsonb_array_elements(coalesce(prior.snapshot,'[]')) old
    where not exists(select 1 from jsonb_array_elements(items) incoming where incoming->>'sku'=old->>'sku');
  if exists(select 1 from unnest(coalesce(missing,'{}')) sku where not sku=any(removed)) then raise exception 'SKU removal requires explicit confirmation';end if;
  next_version=coalesce(prior.version,0)+1;
  insert into public.store_feeds(store_id,version,source_xml,source_hash,snapshot) values(store,next_version,xml,hash,items)
    on conflict(store_id) do update set version=excluded.version,source_xml=excluded.source_xml,source_hash=excluded.source_hash,snapshot=excluded.snapshot,overrides='{}',updated_at=now();
  update public.price_changes set state='rejected' where store_id=store and state='preview';
  return jsonb_build_object('version',next_version,'products',jsonb_array_length(items));
end $$;

create function public.publish_price_change(change uuid,actor uuid,automatic boolean default false) returns jsonb language plpgsql set search_path='' as $$
declare proposal public.price_changes;rule public.price_rules;feed public.store_feeds;current_value bigint;floor_price bigint;begin
  select * into proposal from public.price_changes where id=change;
  if not found then raise exception 'Proposal not found';end if;
  perform 1 from public.stores s where s.id=proposal.store_id and s.owner_id=actor for update;
  if not found then raise exception 'Store not found';end if;
  select * into proposal from public.price_changes where id=change for update;
  if proposal.state='published' then return to_jsonb(proposal);end if;
  if proposal.state<>'preview' or proposal.expires_at<=now() then raise exception 'Proposal expired or blocked. Refresh the calculation.';end if;
  select * into rule from public.price_rules where id=proposal.rule_id for update;
  select * into feed from public.store_feeds where store_id=proposal.store_id for update;
  if feed.version<>proposal.feed_version or rule.updated_at<>proposal.rule_updated_at or not rule.enabled or (automatic and not rule.auto_enabled) then raise exception 'Feed or rule changed. Refresh the calculation.';end if;
  select coalesce((feed.overrides->proposal.sku->>proposal.city_id)::bigint,(item->'prices'->>proposal.city_id)::bigint) into current_value
    from jsonb_array_elements(feed.snapshot) item where item->>'sku'=proposal.sku;
  if current_value is null or current_value<>proposal.current_price then raise exception 'Current price changed. Refresh the calculation.';end if;
  floor_price=greatest(rule.min_price,ceil((rule.cost::numeric+rule.shipping)*10000/(10000-rule.commission_bp-rule.tax_bp-rule.margin_bp)));
  if proposal.suggested_price is null or proposal.suggested_price<floor_price or proposal.suggested_price>rule.max_price or
     abs(proposal.suggested_price-current_value)::numeric*10000>current_value::numeric*rule.max_change_bp then raise exception 'Price safety limits failed';end if;
  update public.store_feeds set overrides=jsonb_set(overrides,array[proposal.sku],coalesce(overrides->proposal.sku,'{}')||jsonb_build_object(proposal.city_id,proposal.suggested_price),true),updated_at=now() where store_id=proposal.store_id;
  update public.price_changes set state='published',published_at=now() where id=change returning * into proposal;
  return to_jsonb(proposal);
end $$;

