create function public.commit_collection_page(input jsonb) returns jsonb language plpgsql set search_path='' as $$
declare task public.collection_tasks;run public.collection_runs;item jsonb;v_product_id bigint;old_price numeric;
  added integer=0;inserted integer;new_found integer;next_state text='running';
  v_run_id uuid=(input->>'runId')::uuid;category bigint=(input->>'categoryId')::bigint;
  page_number integer=(input->>'page')::integer;total integer=(input->>'total')::integer;v_page_size integer=(input->>'pageSize')::integer;
  city text=input->>'cityId';observed timestamptz=now();first_total integer;invalid integer;
begin
  select * into run from public.collection_runs where id=v_run_id for share;
  if run.status<>'running' then return jsonb_build_object('stopped',true);end if;
  select * into task from public.collection_tasks t where t.run_id=v_run_id and t.category_id=category for update;
  if not found then raise exception 'Task missing';end if;
  if task.next_page>page_number then return jsonb_build_object('duplicate',true,'nextPage',task.next_page);end if;
  if task.next_page<>page_number then raise exception 'Unexpected page checkpoint';end if;
  insert into public.collection_pages(run_id,category_id,page,signature) values(v_run_id,category,page_number,input->>'signature');
  for item in select * from jsonb_array_elements(input->'products') loop
    update public.products set product_key=item->>'product_key' where product_key=item->>'legacy_key'
      and not exists(select 1 from public.products where product_key=item->>'product_key');
    insert into public.products(category_id,name,price,parsed_price,brand,rating,reviews_count,image_url,external_id,product_url,product_key,city_id,scraped_at)
    values(category,item->>'name',item->>'price',(item->>'parsed_price')::numeric,item->>'brand',(item->>'rating')::numeric,
      (item->>'reviews_count')::bigint,item->>'image_url',item->>'external_id',item->>'product_url',item->>'product_key',city,observed)
    on conflict(product_key) do update set name=excluded.name,price=excluded.price,parsed_price=excluded.parsed_price,
      brand=excluded.brand,rating=excluded.rating,reviews_count=excluded.reviews_count,image_url=excluded.image_url,
      external_id=excluded.external_id,product_url=excluded.product_url,city_id=excluded.city_id,scraped_at=excluded.scraped_at
    returning id into v_product_id;
    insert into public.product_categories(product_id,category_id) values(v_product_id,category) on conflict do nothing;
    select cp.parsed_price into old_price from public.product_city_prices cp where cp.product_id=v_product_id and cp.city_id=city;
    if (item->>'parsed_price') is not null and old_price is distinct from (item->>'parsed_price')::numeric then
      insert into public.price_history(product_id,city_id,parsed_price,scraped_at) values(v_product_id,city,(item->>'parsed_price')::numeric,observed);
    end if;
    insert into public.product_city_prices(product_id,city_id,parsed_price,scraped_at) values(v_product_id,city,(item->>'parsed_price')::numeric,observed)
      on conflict(product_id,city_id) do update set parsed_price=excluded.parsed_price,scraped_at=excluded.scraped_at;
    insert into public.collection_seen(run_id,category_id,product_id) values(v_run_id,category,v_product_id) on conflict do nothing;
    get diagnostics inserted=row_count;added=added+inserted;
  end loop;
  new_found=task.found_count+added;first_total=coalesce(task.expected_initial,total);invalid=task.invalid_count+coalesce((input->>'invalidCount')::integer,0);
  if (input->>'limited')::boolean and (input->>'hasMore')::boolean then next_state='limited';
  elsif not (input->>'hasMore')::boolean then
    next_state=case when invalid>0 or new_found<greatest(first_total,total) or first_total<>total then 'partial' else 'completed' end;
  end if;
  update public.collection_tasks t set status=next_state,next_page=page_number+1,expected_initial=first_total,
    expected_latest=total,page_size=v_page_size,found_count=new_found,invalid_count=invalid,
    pages_done=t.pages_done+1,error=null,updated_at=observed where t.run_id=v_run_id and t.category_id=category;
  return jsonb_build_object('status',next_state,'found',new_found,'added',added,'saved',jsonb_array_length(input->'products'));
end $$;
revoke execute on function public.commit_collection_page(jsonb) from public,anon,authenticated;
grant execute on function public.commit_collection_page(jsonb) to service_role;

create function public.replace_navigation(nodes jsonb,city text) returns jsonb language plpgsql set search_path='' as $$
declare item jsonb;parent bigint;discovery uuid=gen_random_uuid();leaves integer;begin
  perform pg_advisory_xact_lock(89021001);
  update public.categories set source_active=0 where source_code is not null;
  for item in select * from jsonb_array_elements(nodes) loop
    parent=null;
    if item->>'parent_code' is not null then
      select id into parent from public.categories where source_code=item->>'parent_code';
      if parent is null then raise exception 'Missing navigation parent';end if;
    end if;
    insert into public.categories(name,url,parent_id,level,source_code,source_active,discovered_at)
      values(item->>'name',item->>'url',parent,(item->>'level')::integer,item->>'code',1,now())
      on conflict(source_code) do update set name=excluded.name,url=excluded.url,parent_id=excluded.parent_id,
        level=excluded.level,source_active=1,discovered_at=now();
  end loop;
  select count(*) into leaves from jsonb_array_elements(nodes) n where (n->>'is_leaf')::boolean;
  insert into public.catalog_discoveries(id,city_id,status,finished_at,categories_count,leaves_count)
    values(discovery,city,'completed',now(),jsonb_array_length(nodes),leaves);
  return jsonb_build_object('id',discovery,'categories',jsonb_array_length(nodes),'leaves',leaves);
end $$;

create function public.collection_progress(run uuid) returns jsonb language plpgsql set search_path='' as $$
declare counts jsonb;options jsonb;next_status text;begin
  select r.options into options from public.collection_runs r where id=run;
  select jsonb_build_object('total',count(*),'completed',count(*) filter(where status='completed'),
    'failed',count(*) filter(where status='failed'),'partial',count(*) filter(where status='partial'),
    'limited',count(*) filter(where status='limited'),'pending',count(*) filter(where status='pending'),
    'running',count(*) filter(where status='running'),'cancelled',count(*) filter(where status='cancelled'),
    'pages',coalesce(sum(pages_done),0),'found',coalesce(sum(found_count),0),
    'expected',coalesce(sum(expected_latest),0),'unknown',count(*) filter(where expected_latest is null)) into counts
    from public.collection_tasks where run_id=run;
  if (counts->>'total')::integer>0 and (counts->>'pending')::integer+(counts->>'running')::integer=0 then
    next_status=case when (counts->>'failed')::integer>0 or (counts->>'partial')::integer>0 or
      ((options->>'full')::boolean and (counts->>'completed')::integer<>(counts->>'total')::integer) then 'partial' else 'completed' end;
    update public.collection_runs set status=next_status,finished_at=now(),progress=counts where id=run and status='running';
  else update public.collection_runs set progress=counts where id=run;end if;
  return counts;
end $$;
revoke execute on function public.replace_navigation(jsonb,text),public.collection_progress(uuid) from public,anon,authenticated;
grant execute on function public.replace_navigation(jsonb,text),public.collection_progress(uuid) to service_role;

create function public.create_collection(actor uuid,options jsonb,categories bigint[]) returns uuid language plpgsql set search_path='' as $$
declare run uuid;begin
  if coalesce(array_length(categories,1),0)=0 then raise exception 'No categories selected';end if;
  insert into public.collection_runs(requested_by,options,progress) values(actor,options,jsonb_build_object('total',array_length(categories,1))) returning id into run;
  insert into public.collection_tasks(run_id,category_id,city_id)
    select run,category,options->>'cityId' from unnest(categories) category;
  return run;
end $$;
revoke execute on function public.create_collection(uuid,jsonb,bigint[]) from public,anon,authenticated;
grant execute on function public.create_collection(uuid,jsonb,bigint[]) to service_role;
